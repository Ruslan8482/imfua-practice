USE shop_norm;

-- ------------------------------------------------------------
-- 3.1. Аномалия обновления: город Ивана меняем только в одной строке
-- ------------------------------------------------------------
UPDATE orders_bad
SET customer_city = 'Сочи'
WHERE order_id = 1;

SELECT * FROM orders_bad WHERE customer_name = 'Иван';
-- Результат: у Ивана два города — «Сочи» и «Москва».

-- ------------------------------------------------------------
-- 3.2. Аномалия удаления: удаляем один заказ Марии (последний по дате)
-- ------------------------------------------------------------
DELETE FROM orders_bad WHERE order_id = 4;

SELECT * FROM orders_bad WHERE customer_name = 'Мария';
-- Информация о Марии пока осталась (order_id = 3).
-- Если удалить и второй заказ — Мария исчезнет из базы совсем.
-- Этого НЕ делаем, чтобы сохранить данные для нормализации.

-- ------------------------------------------------------------
-- 3.3. Аномалия вставки: клиент без заказа
-- ------------------------------------------------------------
INSERT INTO orders_bad (customer_name, customer_city)
VALUES ('Новый клиент', 'Тверь');

SELECT * FROM orders_bad WHERE customer_name = 'Новый клиент';
-- Строка есть, но поля заказа = NULL.

-- После демонстрации удаляем тестовую строку (иначе перенос данных упадёт):
DELETE FROM orders_bad WHERE customer_name = 'Новый клиент';

-- ------------------------------------------------------------
-- 3.4. Итог по аномалиям:
--   обновления — один и тот же клиент с разными городами;
--   удаления   — клиент исчезает вместе с последним заказом;
--   вставки    — клиент без заказа возможен только с NULL-полями.
-- ------------------------------------------------------------
SELECT * FROM orders_bad;

